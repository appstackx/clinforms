// 18:30 · lights off: the audit trail, and switching – import from "your current system" (a fictional CSV).
const fs = require("fs");
const path = require("path");
const { Take, L } = require("./rec.cjs");
const originFix = require("./origin-fix.cjs");

(async () => {
  const t = new Take("s6-audit");
  const page = await t.open("sam");
  await originFix(page);
  await page.goto(`${L.APP}/app/clinic/setup/audit`);
  await page.waitForSelector("text=Audit trail >> visible=true");
  await page.waitForTimeout(1000);
  await t.roll();
  t.mark("audit");
  await t.hold(1500);
  await t.moveTo(700, 640, 900);
  await t.scrollTo(380, 1400);
  t.mark("audit-rows");
  await t.hold(1500);
  await t.scrollTo(1100, 2200);
  await t.hold(2000);
  await t.cut();
  // import
  const headers = ["LegacyID", "PatientFirstName", "PatientSurname", "DOB", "MobileTel", "EmailAddr", "Addr1", "PCode"];
  const first = ["Margaret", "Owen", "Ruth", "Sam", "Evie", "Arthur", "Nina", "Theo"];
  const rows = [];
  for (let i = 1; i <= 24; i++) rows.push([`L-${100480 + i}`, first[i % 8], `Fictional${i}`, `${String((i % 27) + 1).padStart(2, "0")}/03/19${60 + i}`, `07700 900${String(700 + i)}`, `import${i}@example.com`, `${i} Mill Lane (fictional)`, "MK3 9ZZ"]);
  rows.push(["L-200001", "", "", "01/01/1980", "", "", "", ""]);
  rows.push(["L-200002", "Ida", "Fictional", "31/02/1975", "", "", "", ""]);
  const file = path.join(t.dir, "patients-from-current-system-fictional.csv");
  fs.writeFileSync(file, [headers, ...rows].map((r) => r.join(",")).join("\r\n") + "\r\n");
  await page.goto(`${L.APP}/app/clinic/setup/import`);
  await page.waitForSelector("[data-testid=import-upload]");
  await page.waitForTimeout(800);
  await t.roll();
  t.mark("import");
  await t.hold(1500);
  await t.moveToLoc(page.locator("#im-file"), 800);
  await t.hold(300);
  await page.setInputFiles("#im-file", file);
  await page.waitForSelector("[data-testid=import-file-summary]");
  t.mark("file");
  await t.hold(1500);
  await t.click(page.locator("[data-testid=import-continue]"), { mark: "continue" });
  await page.waitForSelector("[data-testid=import-mapping]", { timeout: 30000 });
  await page.waitForTimeout(800);
  t.mark("mapping");
  await t.moveToLoc(page.locator("text=/We matched/").first(), 900);
  await t.hold(2400);
  await t.click(page.locator("[data-testid=import-check]"), { mark: "check" });
  await page.waitForSelector("[data-testid=import-counts]", { timeout: 60000 });
  await page.waitForSelector("[data-testid=import-issues] li", { timeout: 30000 });
  await page.waitForTimeout(800);
  t.mark("checked");
  await t.moveToLoc(page.locator("[data-testid=import-counts]"), 900);
  await t.hold(1800);
  await t.moveToLoc(page.locator("[data-testid=import-issues]"), 900);
  await t.hold(2500);
  await t.shot("checked");
  await t.close();
})().catch((e) => { console.error(e); process.exit(1); });
